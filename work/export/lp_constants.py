"""Print the constants ffportrait.cpp needs from LivePortrait's generator, as C++.

The CPU half of lp_gencut (ffportrait::hourglassInput) rebuilds the dense-motion
hourglass's input, so it needs exactly what the graph used: the 1x1x1 `compress` conv
(BatchNorm already folded in upstream's export), and the identity grid, which upstream
stored at fp16 precision -- it is NOT a float32 linspace (-0.9682617 where linspace says
-0.968254), so it is copied, not recomputed. The keypoint variance is fp16-rounded too.

    py -3.10 work/export/lp_constants.py > constants.txt   (then paste into ffportrait.cpp)
"""
import os

import numpy
import onnx
from onnx import numpy_helper

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))


def number(v):
	s = '%.9g' % float(v)   # 9 significant digits round-trips every float32
	return s + ('f' if ('.' in s or 'e' in s) else '.0f')


def literal(values, per_line=6):
	items = [number(v) for v in numpy.ravel(values)]
	lines = [', '.join(items[i:i + per_line]) for i in range(0, len(items), per_line)]
	return '    ' + ',\n    '.join(lines)


def main():
	m = onnx.load(os.path.join(ROOT, 'onnx', 'lp_generator.onnx'))
	inits = {t.name: numpy_helper.to_array(t) for t in m.graph.initializer}
	nodes = {n.output[0]: n for n in m.graph.node}
	conv = nodes['/model/dense_motion_network/compress/Conv_output_0']
	weight = inits[conv.input[1]].reshape(4, 32)
	bias = inits[conv.input[2]]
	sub = nodes['/model/dense_motion_network/Sub_output_0']
	grid = inits[sub.input[0]][0, 0]
	gx, gy, gz = grid[0, 0, :, 0], grid[0, :, 0, 1], grid[:, 0, 0, 2]
	assert numpy.array_equal(grid[..., 0], numpy.broadcast_to(gx, grid.shape[:3]))
	assert numpy.array_equal(grid[..., 1], numpy.broadcast_to(gy[:, None], grid.shape[:3]))
	assert numpy.array_equal(grid[..., 2], numpy.broadcast_to(gz[:, None, None], grid.shape[:3]))
	div = nodes['/model/dense_motion_network/Div_3_output_0']
	variance = float(inits[div.input[1]])
	print('// generated by work/export/lp_constants.py from work/onnx/lp_generator.onnx')
	rows = ',\n'.join('  {\n%s}' % literal(r) for r in weight)
	print('constexpr float kCompressWeight[kCompress][kFeatureChannels] = {\n%s};' % rows)
	print('constexpr float kCompressBias[kCompress] = {\n%s};' % literal(bias))
	print('constexpr float kGridX[kW] = {\n%s};' % literal(gx))
	print('constexpr float kGridY[kH] = {\n%s};' % literal(gy))
	print('constexpr float kGridZ[kD] = {\n%s};' % literal(gz))
	print('constexpr float kKeypointVariance = %s;' % number(variance))


if __name__ == '__main__':
	main()
